#!/usr/bin/env python3
"""
build_pages.py: makes shared links show a proper title and summary.

Run it from this folder after adding, renaming or removing a writing piece:

    python3 build_pages.py

For each section (/experience, /writing, ...) and each piece in
writing/posts.json it writes a small page holding the title and summary
that LinkedIn, Slack, iMessage and search engines read. Visitors are sent
straight on to the full site, which opens the right section or piece.
"""
import html, json, os, shutil

SITE = "https://henrypcb.github.io"
NAME = "Henry"
MARK = "<!-- generated by build_pages.py -->"

SECTIONS = {
    "experience":  ("Experience", "Henry's experience in growth, strategy and research at Monzo and Klarna."),
    "projects":    ("Projects", "Selected projects by Henry."),
    "writing":     ("Writing", "Essays and notes by Henry on growth, strategy and research."),
    "photography": ("Photography", "Photography by Henry."),
}

def page(title, desc, path, kind="website", date=None):
    e = lambda s: html.escape(s, quote=True)
    url = SITE + path
    extra = f'\n<meta property="article:published_time" content="{e(date)}">' if date else ""
    return f"""<!DOCTYPE html>
{MARK}
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{e(title)}</title>
<meta name="description" content="{e(desc)}">
<link rel="canonical" href="{e(url)}">
<meta property="og:site_name" content="{e(NAME)}">
<meta property="og:type" content="{kind}">
<meta property="og:title" content="{e(title)}">
<meta property="og:description" content="{e(desc)}">
<meta property="og:url" content="{e(url)}">{extra}
<meta name="twitter:card" content="summary">
<meta name="twitter:title" content="{e(title)}">
<meta name="twitter:description" content="{e(desc)}">
<script>
  try {{ sessionStorage.setItem('redirect', location.pathname + location.search + location.hash); }} catch (e) {{}}
  location.replace('/');
</script>
<noscript><meta http-equiv="refresh" content="0; url=/"></noscript>
</head>
<body></body>
</html>
"""

def write(folder, content):
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, "index.html"), "w") as f:
        f.write(content)

here = os.path.dirname(os.path.abspath(__file__))
os.chdir(here)

for slug, (label, desc) in SECTIONS.items():
    write(slug, page(f"{label} — {NAME}", desc, f"/{slug}"))

projects = json.load(open("projects/projects.json"))
live_projects = set()
for p in projects:
    if p.get("live"):
        live_projects.add(p["slug"])
        write(os.path.join("projects", p["slug"]),
              page(f'{p["title"]} — {NAME}', p.get("summary", ""), f'/projects/{p["slug"]}'))

posts = json.load(open("writing/posts.json"))
slugs = set()
for p in posts:
    slugs.add(p["slug"])
    write(os.path.join("writing", p["slug"]),
          page(f'{p["title"]} — {NAME}', p["summary"], f'/writing/{p["slug"]}', "article", p.get("date")))

# Tidy up pages for pieces that no longer exist
removed = 0
for entry in os.listdir("writing"):
    folder = os.path.join("writing", entry)
    idx = os.path.join(folder, "index.html")
    if os.path.isdir(folder) and entry not in slugs and os.path.exists(idx):
        if MARK in open(idx).read():
            try:
                shutil.rmtree(folder); removed += 1
            except OSError:
                print(f"Couldn't remove old page for '{entry}'; delete the writing/{entry} folder yourself.")

for entry in os.listdir("projects"):
    folder = os.path.join("projects", entry)
    idx = os.path.join(folder, "index.html")
    if os.path.isdir(folder) and entry not in live_projects and os.path.exists(idx):
        if MARK in open(idx).read():
            try:
                shutil.rmtree(folder); removed += 1
            except OSError:
                print(f"Couldn't remove old page for '{entry}'; delete the projects/{entry} folder yourself.")

print(f"Made {len(SECTIONS)} section pages, {len(live_projects)} project pages and {len(posts)} writing pages." + (f" Removed {removed} old." if removed else ""))
